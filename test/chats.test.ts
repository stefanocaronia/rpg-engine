// The chats of the game copied into the campaign as text (T-225): the player's words and the master's, from Claude Code and Codex, never their tools or
// reasoning; a chat copied again only once it changed.
import { mkdirSync, readdirSync, readFileSync, utimesSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { chatFolders, keepChats } from "../src/chats/index.ts";
import { runCommandLine } from "../src/cli/command-line.ts";
import { copyChats } from "../src/commands/shared/campaign/chats.ts";
import type { ChatFolders, Context } from "../src/core/context.ts";
import { chatKeeper } from "../src/server/chats.ts";
import { makeTempFolder, removeMadeFolders, testContext } from "./support.ts";

afterEach(removeMadeFolders);

/** A campaign's folder, the hosts' folders and the sessions folder the chats go to, all in a folder of their own. */
function world(): { root: string; folders: ChatFolders; target: string; }
{
    const folder = makeTempFolder();
    const root = join(folder, "Le Ombre del Sentiero");
    mkdirSync(root);
    return { root, folders: { claudeCode: join(folder, "claude", "projects"), codex: join(folder, "codex", "sessions") }, target: join(root, "sessions") };
}

/** Writes a chat file of JSON lines, with the folders it needs. */
function chatFile(path: string, lines: unknown[]): void
{
    mkdirSync(join(path, ".."), { recursive: true });
    writeFileSync(path, lines.map((line) => JSON.stringify(line)).join("\n") + "\n");
}

function claudeLine(type: "user" | "assistant", at: string, content: unknown, more: Record<string, unknown> = {}): unknown
{
    return { type, timestamp: at, isSidechain: false, message: { role: type, content }, ...more };
}

function codexLine(at: string, role: string, text: string): unknown
{
    return { timestamp: at, type: "response_item", payload: { type: "message", role, content: [{ type: role === "assistant" ? "output_text" : "input_text", text }] } };
}

const claudeChat = [
    { type: "queue-operation", timestamp: "2026-11-19T20:00:00.000Z" },
    claudeLine("user", "2026-11-19T20:00:01.000Z", "Entro nella locanda.\n<system-reminder>The dashboard is open.</system-reminder>"),
    claudeLine("assistant", "2026-11-19T20:00:02.000Z", [{ type: "thinking", thinking: "the innkeeper hides a key" }]),
    claudeLine("assistant", "2026-11-19T20:00:03.000Z", [{ type: "text", text: "Il fuoco crepita." }, { type: "tool_use", name: "mcp__rpg__roll", input: {} }]),
    claudeLine("user", "2026-11-19T20:00:04.000Z", [{ type: "tool_result", content: "secret: the key is under the bar" }]),
    claudeLine("assistant", "2026-11-19T20:00:05.000Z", [{ type: "text", text: "L'oste ti guarda storto." }]),
    claudeLine("user", "2026-11-19T20:00:06.000Z", "<command-name>/mcp</command-name>"),
    claudeLine("user", "2026-11-19T20:00:07.000Z", "Caveat: generated by local commands", { isMeta: true }),
    claudeLine("assistant", "2026-11-19T20:00:08.000Z", [{ type: "text", text: "A subagent's words." }], { isSidechain: true }),
    claudeLine("user", "2026-11-19T20:00:09.000Z", [{ type: "text", text: "Chiedo una stanza." }]),
    "a line being written {",
];

describe("the chats copied into the campaign (T-225)", () => {
    it("copies a Claude Code chat as the player's words and the master's, without tools, reasoning, subagents or what Claude Code adds", () => {
        const { root, folders, target } = world();
        const projects = join(folders.claudeCode, root.replace(/[^a-zA-Z0-9]/g, "-"));
        chatFile(join(projects, "6c8687ce-e1e1-43fe-98ba-42527dfe1e5a.jsonl"), claudeChat);
        chatFile(join(projects, "6c8687ce-e1e1-43fe-98ba-42527dfe1e5a", "subagents", "agent-1.jsonl"), [claudeLine("user", "2026-11-19T20:00:00.000Z", "A subagent's brief.")]);
        chatFile(join(folders.claudeCode, "another-folder", "11111111-1111-1111-1111-111111111111.jsonl"), [claudeLine("user", "2026-11-19T20:00:00.000Z", "Another project.")]);

        expect(keepChats(root, target, folders, process.platform, [])).toBe(1);
        expect(readdirSync(target)).toEqual(["2026-11-19 claude-code 7dfe1e5a.md"]);
        expect(readFileSync(join(target, "2026-11-19 claude-code 7dfe1e5a.md"), "utf8")).toBe(
            [
                "# 2026-11-19 · claude-code",
                "",
                "Written by rpg from the chat claude-code keeps (6c8687ce-e1e1-43fe-98ba-42527dfe1e5a), again as it goes on: a change made here does not last.",
                "",
                "**Player** · 2026-11-19 20:00:01 UTC",
                "",
                "Entro nella locanda.",
                "",
                "**Master** · 2026-11-19 20:00:03 UTC",
                "",
                "Il fuoco crepita.",
                "",
                "L'oste ti guarda storto.",
                "",
                "**Player** · 2026-11-19 20:00:09 UTC",
                "",
                "Chiedo una stanza.",
                "",
            ].join("\n"),
        );
    });

    it("copies a Codex chat started in the campaign's folder, not another folder's, a subagent's, nor the instructions Codex sends as the player's", () => {
        const { root, folders, target } = world();
        const day = join(folders.codex, "2026", "11", "19");
        const meta = (cwd: string, more: Record<string, unknown> = {}): unknown => ({ timestamp: "2026-11-19T21:00:00.000Z", type: "session_meta", payload: { cwd, ...more } });
        chatFile(join(day, "rollout-2026-11-19T21-00-00-01a1dc78-cfaf-7a02-87d2-cf051a215df9.jsonl"), [
            meta(root.toUpperCase()),
            codexLine("2026-11-19T21:00:01.000Z", "developer", "You are Codex."),
            codexLine("2026-11-19T21:00:01.000Z", "user", "# AGENTS.md instructions for the campaign"),
            codexLine("2026-11-19T21:00:01.000Z", "user", "<environment_context>windows</environment_context>"),
            codexLine("2026-11-19T21:00:02.000Z", "user", "Apro la porta."),
            { timestamp: "2026-11-19T21:00:03.000Z", type: "response_item", payload: { type: "reasoning", summary: [{ text: "a trap" }] } },
            codexLine("2026-11-19T21:00:04.000Z", "assistant", "La porta cigola."),
        ]);
        chatFile(join(day, "rollout-2026-11-19T21-00-00-01a1dc78-0bc4-7030-88f0-d9edf531a02c.jsonl"), [meta(root, { parent_thread_id: "01a1dc78" }), codexLine("2026-11-19T21:00:02.000Z", "user", "A subagent.")]);
        chatFile(join(day, "rollout-2026-11-19T21-00-00-01a1dc78-0bc4-7030-88f0-aaaaaaaaaaaa.jsonl"), [meta(join(root, "..")), codexLine("2026-11-19T21:00:02.000Z", "user", "Elsewhere.")]);

        // A folder's name in another case is the same folder only on Windows.
        expect(keepChats(root, target, folders, "win32", [])).toBe(1);
        const text = readFileSync(join(target, "2026-11-19 codex 1a215df9.md"), "utf8");
        expect(text).toContain("**Player** · 2026-11-19 21:00:02 UTC\n\nApro la porta.\n\n**Master** · 2026-11-19 21:00:04 UTC\n\nLa porta cigola.\n");
        expect(text).not.toMatch(/AGENTS|environment|Codex\.|trap|subagent|Elsewhere/);
    });

    it("copies a chat again only once it changed, and leaves out one with no words yet", () => {
        const { root, folders, target } = world();
        const path = join(folders.claudeCode, root.replace(/[^a-zA-Z0-9]/g, "-"), "6c8687ce-e1e1-43fe-98ba-42527dfe1e5a.jsonl");
        chatFile(path, [{ type: "queue-operation", timestamp: "2026-11-19T20:00:00.000Z" }]);
        expect(keepChats(root, target, folders, process.platform, [])).toBe(0);

        chatFile(path, claudeChat);
        utimesSync(path, new Date("2026-11-19T20:00:00Z"), new Date("2026-11-19T20:00:00Z"));
        expect(keepChats(root, target, folders, process.platform, [])).toBe(1);
        expect(keepChats(root, target, folders, process.platform, [])).toBe(0);

        chatFile(path, [...claudeChat, claudeLine("assistant", "2026-11-20T09:00:00.000Z", [{ type: "text", text: "Il giorno dopo." }])]);
        utimesSync(path, new Date(Date.now() + 60_000), new Date(Date.now() + 60_000));
        expect(keepChats(root, target, folders, process.platform, [])).toBe(1);
        expect(readdirSync(target)).toEqual(["2026-11-19 claude-code 7dfe1e5a.md"]);
        expect(readFileSync(join(target, "2026-11-19 claude-code 7dfe1e5a.md"), "utf8")).toContain("Il giorno dopo.");
    });

    it("copies them as the server starts, then at most every five minutes, after a call and apart from it; never without the hosts' folders", async () => {
        const { root, folders, target } = world();
        writeFileSync(join(root, "campaign.yaml"), "name: Sentiero\n");
        mkdirSync(target);
        const path = join(folders.claudeCode, root.replace(/[^a-zA-Z0-9]/g, "-"), "6c8687ce-e1e1-43fe-98ba-42527dfe1e5a.jsonl");
        chatFile(path, claudeChat);
        let now = Date.parse("2026-11-19T20:00:00Z");
        const context = { ...testContext(root), now: () => new Date(now) };
        const settle = (): Promise<void> => new Promise((done) => setTimeout(done, 20));

        chatKeeper(context)();
        await settle();
        expect(readdirSync(target)).toEqual([]);

        const keep = chatKeeper({ ...context, chatFolders: folders });
        keep();
        expect(readdirSync(target)).toEqual([]);
        await settle();
        expect(readdirSync(target)).toEqual(["2026-11-19 claude-code 7dfe1e5a.md"]);

        chatFile(path, [...claudeChat, claudeLine("assistant", "2026-11-19T20:01:00.000Z", [{ type: "text", text: "Più tardi." }])]);
        utimesSync(path, new Date(Date.now() + 60_000), new Date(Date.now() + 60_000));
        now += 4 * 60_000;
        keep();
        await settle();
        expect(readFileSync(join(target, "2026-11-19 claude-code 7dfe1e5a.md"), "utf8")).not.toContain("Più tardi.");
        now += 60_000;
        keep();
        await settle();
        expect(readFileSync(join(target, "2026-11-19 claude-code 7dfe1e5a.md"), "utf8")).toContain("Più tardi.");
    });

    it("finds the hosts' folders in the player's home, or where the environment moves them", () => {
        expect(chatFolders({}, join("/home", "lia"))).toEqual({ claudeCode: join("/home", "lia", ".claude", "projects"), codex: join("/home", "lia", ".codex", "sessions") });
        expect(chatFolders({ CLAUDE_CONFIG_DIR: join("/c"), CODEX_HOME: join("/x") }, join("/home", "lia"))).toEqual({ claudeCode: join("/c", "projects"), codex: join("/x", "sessions") });
    });
});

describe("chats, the past chats read back (T-225)", () => {
    /** A campaign whose save 1 was made at 20:30, then loaded at 21:00; a chat from 20:00 to 21:10 copied from Claude Code. */
    async function campaignWithLoad(): Promise<{ rpg: (...args: string[]) => Promise<string>; root: string; }>
    {
        const { root, folders } = world();
        let now = Date.parse("2026-11-19T20:30:00Z");
        const context: Context = { ...testContext(root), now: () => new Date(now), chatFolders: folders };
        const rpg = async (...args: string[]): Promise<string> => (await runCommandLine(args, context)).output;
        await rpg("init", "--name", "Sentiero", "--language", "it", "--system", "fake", "--difficulty", "normal", "--lethality", "dice");
        await rpg("config", "saves", "free");
        await rpg("save", "make");
        const save = readdirSync(join(root, ".saves")).find((file) => file.startsWith("001")) ?? "";
        utimesSync(join(root, ".saves", save), new Date("2026-11-19T20:30:00Z"), new Date("2026-11-19T20:30:00Z"));
        now = Date.parse("2026-11-19T21:00:00Z");
        await rpg("save", "load", "1");
        chatFile(join(folders.claudeCode, root.replace(/[^a-zA-Z0-9]/g, "-"), "6c8687ce-e1e1-43fe-98ba-42527dfe1e5a.jsonl"), [
            claudeLine("user", "2026-11-19T20:00:00.000Z", "Guardo il plettro."),
            claudeLine("assistant", "2026-11-19T20:00:05.000Z", [{ type: "text", text: "Sul plettro sono incise due iniziali: E. M." }]),
            claudeLine("user", "2026-11-19T20:45:00.000Z", "Rompo il plettro."),
            claudeLine("assistant", "2026-11-19T20:45:05.000Z", [{ type: "text", text: "Il plettro si spezza in due." }]),
            claudeLine("user", "2026-11-19T21:10:00.000Z", "Rimetto il plettro in tasca."),
        ]);
        copyChats(root, context);
        return { rpg, root };
    }

    it("marks in the copy what a loaded save undid, from when the save was made to when it was loaded", async () => {
        const { root } = await campaignWithLoad();
        const text = readFileSync(join(root, "sessions", "2026-11-19 claude-code 7dfe1e5a.md"), "utf8");
        expect(text).toContain("**Player** · 2026-11-19 20:00:00 UTC\n\nGuardo il plettro.");
        expect(text).toContain("**Player** · 2026-11-19 20:45:00 UTC · undone by loading save 1\n\nRompo il plettro.");
        expect(text).toContain("**Player** · 2026-11-19 21:10:00 UTC\n\nRimetto il plettro in tasca.");
    });

    it("finds passages by their words, the newest first, without what a load undid, and reads a day in order, or lists the days", async () => {
        const { rpg } = await campaignWithLoad();
        expect(await rpg("chats", "plettro")).toBe(
            [
                "2026-11-19 21:10 Player: Rimetto il plettro in tasca.",
                "2026-11-19 20:00 Master: Sul plettro sono incise due iniziali: E. M.",
                "2026-11-19 20:00 Player: Guardo il plettro.",
                "2 messages of what a loaded save undid are left out: they did not happen.",
            ].join("\n\n"),
        );
        expect(await rpg("chats", "INIZIALI incise")).toBe("2026-11-19 20:00 Master: Sul plettro sono incise due iniziali: E. M.");
        expect(await rpg("chats", "drago")).toBe("No chat holds those words. What happened only in this chat is yours already.");
        expect(await rpg("chats")).toBe("Days with chats, the newest first (give one as day to read it):\n2026-11-19: 3 messages\n\n2 messages of what a loaded save undid are left out: they did not happen.");
        expect(await rpg("chats", "--day", "2026-11-19", "--from", "20:00:05")).toBe(
            "20:00:05 Master: Sul plettro sono incise due iniziali: E. M.\n\n21:10:00 Player: Rimetto il plettro in tasca.\n\n2 messages of what a loaded save undid are left out: they did not happen.",
        );
    });
});
